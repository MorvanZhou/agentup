const RECENT_STORAGE_KEY = "agentup.composer.recent-emoji";
const RECENT_LIMIT = 24;

/** 在光标处插入表情。 */
export function insertEmojiAt(
  text: string,
  cursor: number,
  emoji: string,
): { text: string; cursor: number } {
  const start = Math.max(0, Math.min(cursor, text.length));
  return {
    text: `${text.slice(0, start)}${emoji}${text.slice(start)}`,
    cursor: start + emoji.length,
  };
}

export function loadRecentEmojis(): string[] {
  if (typeof localStorage === "undefined") return [];
  try {
    const raw = localStorage.getItem(RECENT_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((item): item is string => typeof item === "string").slice(0, RECENT_LIMIT);
  } catch {
    return [];
  }
}

/** 记入最近使用，返回更新后的列表（最新在前）。 */
export function rememberRecentEmoji(emoji: string): string[] {
  const next = [emoji, ...loadRecentEmojis().filter((item) => item !== emoji)].slice(
    0,
    RECENT_LIMIT,
  );
  if (typeof localStorage !== "undefined") {
    try {
      localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(next));
    } catch {
      /* 配额满等忽略 */
    }
  }
  return next;
}

/** 「常用」分类：最近使用优先，不足用默认种子补齐。 */
export function buildFrequentEmojis(recent: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const emoji of [...recent, ...DEFAULT_FREQUENT_EMOJIS]) {
    if (seen.has(emoji)) continue;
    seen.add(emoji);
    out.push(emoji);
    if (out.length >= RECENT_LIMIT) break;
  }
  return out;
}

/**
 * 拆出 emoji 序列（含 ZWJ / 色调修饰），便于输入区/气泡里单独放大。
 * 非 emoji 文本原样保留。
 */
export type EmojiTextPiece =
  | { type: "text"; value: string }
  | { type: "emoji"; value: string };

const EMOJI_SEQUENCE_RE =
  /(?:\p{Extended_Pictographic}(?:\uFE0F|\uFE0E)?(?:\u200D\p{Extended_Pictographic}(?:\uFE0F|\uFE0E)?)*)|\p{Regional_Indicator}{2}/gu;

export function splitEmojiText(text: string): EmojiTextPiece[] {
  if (!text) return [];
  const pieces: EmojiTextPiece[] = [];
  let last = 0;
  for (const match of text.matchAll(EMOJI_SEQUENCE_RE)) {
    const start = match.index ?? 0;
    if (start > last) pieces.push({ type: "text", value: text.slice(last, start) });
    pieces.push({ type: "emoji", value: match[0] });
    last = start + match[0].length;
  }
  if (last < text.length) pieces.push({ type: "text", value: text.slice(last) });
  return pieces.length ? pieces : [{ type: "text", value: text }];
}
